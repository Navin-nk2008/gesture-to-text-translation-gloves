import numpy as np
import pandas as pd

SEQUENCE_LENGTH = 100

def generate_none_sequence():
    flex = np.ones((SEQUENCE_LENGTH, 4)) * 1023

    imu = np.random.normal(0, 150, (SEQUENCE_LENGTH, 6))

    # drift
    drift = np.linspace(0, np.random.uniform(-300, 300), SEQUENCE_LENGTH).reshape(-1,1)
    imu += drift

    # tiny motion
    t = np.linspace(0, 2*np.pi, SEQUENCE_LENGTH)
    imu[:, 0] += 300 * np.sin(t)
    imu[:, 1] += 250 * np.cos(t)

    # small spikes
    for _ in range(np.random.randint(1, 4)):
        idx = np.random.randint(0, SEQUENCE_LENGTH)
        imu[idx] += np.random.normal(0, 800, 6)

    imu = np.clip(imu, -20000, 20000)

    return np.concatenate([flex, imu], axis=1)


def generate_none_dataset(num_sequences=12):
    all_data = []

    for _ in range(num_sequences):
        seq = generate_none_sequence()
        for row in seq:
            all_data.append(list(row) + ["NONE"])

    columns = [
        "flex1","flex2","flex3","flex4",
        "ax","ay","az","gx","gy","gz",
        "label"
    ]

    df = pd.DataFrame(all_data, columns=columns)
    df.to_csv("none.csv", index=False)

    print("Saved none.csv with", num_sequences, "sequences")


