SEQUENCE_LENGTH = 100


# 🔹 LOAD DATA
def load_data(files):
    X, y = [], []

    for file in files:
        df = pd.read_csv(file)

        data = df.iloc[:, :-1].values.astype(np.float32)
        labels = df.iloc[:, -1].values

        for i in range(0, len(data), SEQUENCE_LENGTH):
            seq = data[i:i+SEQUENCE_LENGTH]
            if len(seq) == SEQUENCE_LENGTH:
                X.append(seq)
                y.append(labels[i])

