import numpy as np
import pandas as pd
from scipy.interpolate import interp1d

SEQUENCE_LENGTH = 100
AUG_PER_SEQ = 5


def load_sequences(file):
    df = pd.read_csv(file)
    data = df.iloc[:, 1:-1].values
    label = df.iloc[0, -1]

    sequences = []
    for i in range(0, len(data), SEQUENCE_LENGTH):
        seq = data[i:i+SEQUENCE_LENGTH]
        if len(seq) == SEQUENCE_LENGTH:
            sequences.append(seq)

    return sequences, label


def time_warp(seq):
    t_original = np.linspace(0, 1, SEQUENCE_LENGTH)
    scale = np.random.uniform(0.8, 1.2)

    t_new = np.linspace(0, 1, int(SEQUENCE_LENGTH * scale))
    warped = []

    for i in range(seq.shape[1]):
        f = interp1d(t_original, seq[:, i], fill_value="extrapolate")
        temp = f(t_new)

        f2 = interp1d(np.linspace(0,1,len(temp)), temp)
        temp = f2(t_original)

        warped.append(temp)

    return np.stack(warped, axis=1)


def augment_sequence(seq):
    aug = seq.astype(np.float32)

    flex = aug[:, :4]
    imu = aug[:, 4:]

    # 🔹 flex variation
    flex += np.random.normal(0, 5, flex.shape)

    # 🔹 stronger IMU variation
    imu += np.random.normal(0, 800, imu.shape)

    scale = np.random.uniform(0.5, 1.5)
    imu *= scale

    drift = np.random.normal(0, 300, (1, imu.shape[1]))
    imu += drift

    imu += np.random.normal(0, 200, imu.shape)

    combined = np.concatenate([flex, imu], axis=1)
    combined = time_warp(combined)

    imu = combined[:, 4:]
    imu = np.clip(imu, -20000, 20000)

    combined[:, 4:] = imu

    return combined


def generate_augmented(input_file, output_file):
    sequences, label = load_sequences(input_file)
    all_data = []

    for seq in sequences:
        for row in seq:
            all_data.append(list(row) + [label])

        for _ in range(AUG_PER_SEQ):
            aug_seq = augment_sequence(seq)
            for row in aug_seq:
                all_data.append(list(row) + [label])

    columns = [
        "flex1","flex2","flex3","flex4",
        "ax","ay","az","gx","gy","gz",
        "label"
    ]

    pd.DataFrame(all_data, columns=columns).to_csv(output_file, index=False)

    print("Saved:", output_file)


